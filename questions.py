def get_flat_questions(position_key):
    """Возвращает плоский список вопросов с указанием компетенции"""
    pos = QUESTIONS[position_key]
    flat = []
    for competency, questions in pos["competencies"].items():
        for q in questions:
            flat.append({"competency": competency, "question": q})
    return flat


